#!/usr/bin/env python3
"""Generate the iSolarCloud mqtt point table (components/isolarcloud/mqtt_point_table.{h,cpp}).

Input : data/cloud/point_tables.yaml (docs/data_format.md): per cloud table type, the signal
        ids the uplink serialises with their cloud point id, the messages that carry them
        (attributes / rundata / status / general), output format and scale.
Output: a compact rodata table. Rows keep the file order (rundata keys are emitted in table
        order). Tables with identical content share one array.

Needs PyYAML (tools/requirements.txt); deterministic (no timestamps).
tests/test_gen_mqtt_table.py checks that the committed files match a fresh run.

Usage: tools/gen_mqtt_table.py [--yaml PATH] [--out-dir DIR] [--check]   (--check: exit 1 if outputs are stale).
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import datalib  # noqa: E402

ROOT = os.path.dirname(HERE)
DEFAULT_YAML = datalib.CLOUD_POINTS
DEFAULT_OUT = os.path.join(ROOT, "components", "isolarcloud")

# Message names -> MqttMask bits.
ATTR_BITS = {"attributes": 0x1, "rundata": 0x2, "status": 0x40, "general": 0x400}
# Value type names -> sig type codes.
SIG_TYPES = {"s8": 1, "u8": 2, "s16": 3, "u16": 4, "s32": 5, "u32": 6, "s64": 7, "u64": 8,
             "f32": 9, "f64": 10, "str": 12, "none": 0}
FORMATS = {3, 4, 5, 6, 8, 9, 10, 12, 13, 101}


def f64_literal(v):
    r = repr(float(v))
    return r if ("e" in r or "." in r) else r + ".0"


def load(path):
    """-> {table_type: (cloud devType, [(sigid, point, mask, fmt, scale, size, sig_type)])}."""
    doc = datalib.load_cloud_points(path)
    tables = {}
    for t in doc["tables"]:
        tt = int(t["table_type"])
        if tt in tables:
            raise SystemExit("%s: table type 0x%02x listed twice" % (datalib.rel(path), tt))
        rows = []
        for p in t["points"]:
            mask = 0
            for a in p["attrs"]:
                if a not in ATTR_BITS:
                    raise SystemExit("%s: table 0x%02x point %d: unknown attr %r"
                                     % (datalib.rel(path), tt, p["point"], a))
                mask |= ATTR_BITS[a]
            if not mask or p["format"] not in FORMATS or p["type"] not in SIG_TYPES:
                raise SystemExit("%s: table 0x%02x point %d: bad attrs / format / type"
                                 % (datalib.rel(path), tt, p["point"]))
            rows.append((int(p["signal"]), int(p["point"]), mask, int(p["format"]),
                         float(p["scale"]), int(p["size"]), SIG_TYPES[p["type"]]))
        tables[tt] = (int(t["cloud_device_type"]), rows)
    return tables


def generate(yaml_path):
    tables = load(yaml_path)
    scales = sorted({row[4] for _, rows in tables.values() for row in rows})
    sidx = {s: i for i, s in enumerate(scales)}
    assert len(scales) < 256

    # Share identical arrays (first table type in ascending order owns the array).
    arrays = []  # (name, rows)
    owner = {}
    for t in sorted(tables):
        rows = tables[t][1]
        for name, r in arrays:
            if r == rows:
                owner[t] = name
                break
        else:
            name = "kPoints_%02x" % t
            arrays.append((name, rows))
            owner[t] = name

    h = []
    h.append("#pragma once")
    h.append("// GENERATED by tools/gen_mqtt_table.py from data/cloud/point_tables.yaml. Do not edit.")
    h.append("//")
    h.append("// Stock iSolarCloud mqtt point table (cloud_outbound.md C7.1): per stock *table type* (the")
    h.append("// device-model table, e.g. 0x23 hybrid), the DM sigids the cloud receives, with the cloud")
    h.append("// point id (rundata/propertydata key), attr mask, output fmt and scale. Only rows with attr")
    h.append("// mask 0x1 (attributes), 0x2 (rundata), 0x40 (devstatusdata) or 0x400 (generaldata) are kept,")
    h.append("// in stock order.")
    h.append("// size / sig_type are the stock DM declared size and type of the sig (sig_type 0 = the sig")
    h.append("// is not in the stock sig table of that type).")
    h.append("#include <cstddef>")
    h.append("#include <cstdint>")
    h.append("")
    h.append("namespace esphome::isolarcloud {")
    h.append("")
    h.append("enum MqttMask : uint16_t {\n  MQTT_MASK_ATTR = 0x1,\n  MQTT_MASK_RUNDATA = 0x2,\n  MQTT_MASK_STATUS = 0x40,\n  MQTT_MASK_GENERAL = 0x400,\n};")
    h.append("")
    h.append("struct MqttPoint {")
    h.append("  int32_t point_id;   ///< cloud point id (key \"%ld\"); -1 for a few stock placeholder rows")
    h.append("  uint16_t sigid;     ///< DM sig id")
    h.append("  uint16_t size;      ///< stock DM size in bytes")
    h.append("  uint16_t mask;      ///< MqttMask bits")
    h.append("  uint8_t fmt;        ///< output format (cloud_outbound.md C7.2 table)")
    h.append("  uint8_t sig_type;   ///< stock sig type: 1 s8, 2 u8, 3 s16, 4 u16, 5 s32, 6 u32, 7 s64, 8 u64,")
    h.append("                      ///< 9/10 float?, 12 string, other = opaque")
    h.append("  uint8_t scale_idx;  ///< index into kMqttScales")
    h.append("  uint8_t reserved;")
    h.append("};")
    h.append("")
    h.append("struct MqttTable {")
    h.append("  uint16_t table_type;      ///< stock table type (dev_type of the device model)")
    h.append("  uint16_t cloud_dev_type;  ///< businessData devType for this table")
    h.append("  const MqttPoint *points;")
    h.append("  uint16_t count;")
    h.append("};")
    h.append("")
    h.append("extern const double kMqttScales[%d];" % len(scales))
    h.append("extern const MqttTable kMqttTables[%d];" % len(tables))
    h.append("static constexpr size_t NUM_MQTT_TABLES = %d;" % len(tables))
    h.append("")
    h.append("inline double mqtt_scale(const MqttPoint &p) { return kMqttScales[p.scale_idx]; }")
    h.append("/// The table for a stock table type, or nullptr.")
    h.append("const MqttTable *find_mqtt_table(uint16_t table_type);")
    h.append("")
    h.append("}  // namespace esphome::isolarcloud")
    h.append("")

    c = []
    c.append("// GENERATED by tools/gen_mqtt_table.py from data/cloud/point_tables.yaml. Do not edit.")
    c.append('#include "mqtt_point_table.h"')
    c.append("")
    c.append("namespace esphome::isolarcloud {")
    c.append("")
    c.append("const double kMqttScales[%d] = {%s};" % (len(scales), ", ".join(f64_literal(s) for s in scales)))
    c.append("")
    c.append("namespace {")
    c.append("// {point_id, sigid, size, mask, fmt, sig_type, scale_idx, 0}")
    for name, rows in arrays:
        users = ", ".join("0x%02x" % t for t in sorted(tables) if owner[t] == name)
        c.append("// table type(s) %s: %d rows" % (users, len(rows)))
        c.append("const MqttPoint %s[] = {" % name)
        for sig, pid, mask, fmt, scale, size, sty in rows:
            c.append("    {%d, 0x%04x, %d, 0x%x, %d, %d, %d, 0}," % (pid, sig, size, mask, fmt, sty, sidx[scale]))
        c.append("};")
    c.append("}  // namespace")
    c.append("")
    c.append("const MqttTable kMqttTables[%d] = {" % len(tables))
    for t in sorted(tables):
        c.append("    {0x%02x, %d, %s, sizeof(%s) / sizeof(MqttPoint)}," % (t, tables[t][0], owner[t], owner[t]))
    c.append("};")
    c.append("")
    c.append("const MqttTable *find_mqtt_table(uint16_t table_type) {")
    c.append("  for (const auto &t : kMqttTables) {")
    c.append("    if (t.table_type == table_type)")
    c.append("      return &t;")
    c.append("  }")
    c.append("  return nullptr;")
    c.append("}")
    c.append("")
    c.append("}  // namespace esphome::isolarcloud")
    c.append("")
    return "\n".join(h), "\n".join(c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--yaml", default=DEFAULT_YAML)
    ap.add_argument("--out-dir", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if the files in --out-dir are stale")
    a = ap.parse_args()
    hdr, src = generate(a.yaml)
    files = (("mqtt_point_table.h", hdr), ("mqtt_point_table.cpp", src))
    if a.check:
        stale = []
        for name, text in files:
            path = os.path.join(a.out_dir, name)
            old = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
            if old != text:
                stale.append(path)
        if stale:
            print("stale: %s (run tools/gen_mqtt_table.py)" % ", ".join(stale))
            return 1
        return 0
    os.makedirs(a.out_dir, exist_ok=True)
    for name, text in files:
        with open(os.path.join(a.out_dir, name), "w", newline="\n") as f:
            f.write(text)
    print("wrote mqtt_point_table.{h,cpp} to %s" % a.out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
