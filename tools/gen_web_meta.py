#!/usr/bin/env python3
"""Generate components/sungrow_web/web/src/meta.gen.ts from register_meta.py.

The on-device SPA (components/sungrow_web) renders /api/signals, whose keys are bare sigid
hex strings ("0x2080"). This tool bakes the human presentation metadata (label, unit,
device_class, display precision and the HA-normalising multiplier) into a TypeScript module
that esbuild bundles into app.js, so the UI can show real labels + units instead of raw
0xNNNN — mirroring how components/sungrow_mqtt/__init__.py bakes ha_meta_gen.h for the MQTT
publisher.

The map is grouped by family (inverter | battery | charger | energy_bridge | meter | logger)
because the same sigid can mean different things in different families; /api/devices
reports each device's family so the SPA can pick the right table (with a merged fallback).

Values in /api/signals are already table-scaled (Signal::number()); the SPA multiplies by the
baked `mult` to reach the unit shown (e.g. kvar -> var x1000), exactly like the MQTT publisher
(store.get_number() * meta.multiplier).

Run before tools/gen_web_assets.py (which also invokes this automatically). Stdlib only;
output is deterministic (sorted), so a committed meta.gen.ts only changes when the data does.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATAMODEL = HERE.parent / "components" / "sungrow_datamodel" / "register_meta.py"
WRITE_META = HERE.parent / "components" / "sungrow_control" / "write_meta.py"
OUT_TS = HERE.parent / "components" / "sungrow_web" / "web" / "src" / "meta.gen.ts"

# register_meta FAMILIES tuple layout (see register_meta.py docstring):
#   (sigid, name, unit, multiplier, device_class, state_class, accuracy, is_string, type, nreg,
#    bit_parent, bit)
_I_SIGID, _I_NAME, _I_UNIT, _I_MULT, _I_DC, _I_SC, _I_ACC, _I_IS_STR = range(8)
_I_BIT = 11
# register_meta INFO tuple layout: (confidence, category, scope, priority, group, enum).
_INFO_CATEGORY, _INFO_PRIORITY, _INFO_GROUP, _INFO_ENUM = 1, 3, 4, 5
# register_meta READS tuple layout: (regaddr, name, unit, multiplier, device_class, state_class,
#   accuracy, fn, group, priority, enum, scale, dtype).
_R_REGADDR, _R_NAME, _R_UNIT, _R_MULT, _R_DC, _R_ACC, _R_PRIORITY, _R_ENUM, _R_SCALE, _R_DTYPE = (
    0, 1, 2, 3, 4, 6, 9, 10, 11, 12)

DEFAULT_PRIORITY = 9999


def _load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _load_meta():
    """Import register_meta.py in isolation; return (FAMILIES, INFO, ENUMS, READS)."""
    mod = _load_module(DATAMODEL, "_sungrow_register_meta")
    return (mod.FAMILIES, getattr(mod, "INFO", {}), getattr(mod, "ENUMS", {}),
            getattr(mod, "READS", {}))


def _load_state_meta():
    """Import register_meta.py in isolation; return (FAULT_CODES, DEV_STATE_CLASS)."""
    mod = _load_module(DATAMODEL, "_sungrow_register_meta_state")
    return getattr(mod, "FAULT_CODES", {}), getattr(mod, "DEV_STATE_CLASS", {})


def _load_write_meta():
    """Import write_meta.py (PROFILES, KEYS). Returns (profiles, keys) or (None, None)."""
    try:
        mod = _load_module(WRITE_META, "_sungrow_write_meta")
        return getattr(mod, "PROFILES", []), getattr(mod, "KEYS", {})
    except (OSError, AttributeError, RuntimeError):
        return None, None


def _jstr(s: str) -> str:
    """JSON/JS double-quoted string literal (UTF-8 kept verbatim; escape \\ and ")."""
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{out}"'


def _num(x: float) -> str:
    """Compact JS number literal (1.0 -> '1', 0.1 -> '0.1')."""
    f = float(x)
    if f.is_integer():
        return str(int(f))
    return repr(f)


def _enum_literal(name: str, enums: dict) -> str:
    """ENUM table name -> JS `[[raw, label], ...]` literal, or 'null' when absent/empty."""
    table = enums.get(name) if name else None
    if not table:
        return "null"
    return "[" + ", ".join(f"[{int(raw)}, {_jstr(str(label))}]" for raw, label in table) + "]"


def gen(families: dict, info: dict, enums: dict) -> str:
    lines = [
        "// GENERATED by tools/gen_web_meta.py from "
        "components/sungrow_datamodel/register_meta.py — DO NOT EDIT.",
        "// signal key ('0xNNNN' sigid, upper-case, matching /api/signals) -> presentation metadata,",
        "// grouped by device family. Non-polled protection registers are in PROTECTION_READS.",
        "// Tuple: [label, unit, deviceClass, precision, mult, priority, group, enum].",
        "//   precision = display decimals (-1 = unspecified).",
        "//   mult      = HA-normalising multiplier; displayed value = signalValue * mult.",
        "//   priority  = sort-rank (lower = more important; 9999 = unranked).",
        "//   group     = 'realtime' | 'static' | 'protection' | 'hidden' (category:hidden signals).",
        "//   enum      = [[raw, label], ...] read-side decode table, or null.",
        "",
        "export type MetaTuple = [string, string, string, number, number, number, string, "
        "[number, string][] | null];",
        "",
        "export const META: Record<string, Record<string, MetaTuple>> = {",
    ]
    total = 0
    for family in sorted(families):
        lines.append(f"  {_jstr(family)}: {{")
        seen: set[int] = set()
        rows: list[tuple[int, str]] = []
        finfo = info.get(family, {})
        for key, meta in families.get(family, {}).items():
            sigid = meta[_I_SIGID]
            if sigid in seen:  # dedupe by sigid (store keys by sigid); keep first key's label
                continue
            seen.add(sigid)
            label = meta[_I_NAME] or key
            unit = meta[_I_UNIT] or ""
            dc = meta[_I_DC] or ""
            acc = meta[_I_ACC]
            precision = int(acc) if acc is not None else -1
            mult = float(meta[_I_MULT]) if meta[_I_MULT] is not None else 1.0
            ii = finfo.get(key)
            priority = int(ii[_INFO_PRIORITY]) if ii else DEFAULT_PRIORITY
            group = (ii[_INFO_GROUP] if ii else "realtime") or "realtime"
            if ii and ii[_INFO_CATEGORY] == "hidden":  # category:hidden -> hide in SPA/MQTT
                group = "hidden"
            enum = _enum_literal(ii[_INFO_ENUM] if ii else "", enums)
            row = (
                f'    "0x{sigid:04X}": [{_jstr(label)}, {_jstr(unit)}, '
                f"{_jstr(dc)}, {precision}, {_num(mult)}, {priority}, {_jstr(group)}, {enum}],"
            )
            rows.append((sigid, row))
        rows.sort(key=lambda r: r[0])
        lines.extend(r[1] for r in rows)
        lines.append("  },")
        total += len(rows)
    lines.append("};")
    lines.append("")
    lines.append(f"// {total} signals across {len(families)} families.")
    lines.append("")
    return "\n".join(lines)


def gen_reads(reads: dict, enums: dict) -> str:
    """Emit PROTECTION_READS: the non-polled grid-code holding registers (register_meta READS),
    keyed by register address like the values of GET /api/grid_read."""
    lines = [
        "",
        "// --- protection / grid-code registers (from register_meta.py READS) --------------------",
        "// Holding registers stock does not poll, so they are not in /api/signals. The SPA requests",
        "// them with POST /api/grid_read_start?device= (body: the addresses) and reads",
        "// GET /api/grid_read?device=, whose values[].a is the register address and values[].v the",
        "// raw register. Displayed value = raw (as dtype) * scale * mult; raw 0xFFFF (u16) /",
        "// 0x7FFF (s16) = not supported by this inverter (the stock XML `invisible` refs).",
        "// Sorted by priority (lower = more important), then address.",
        "export interface ProtectionRead {",
        "  address: number;",
        "  key: string;",
        "  label: string;",
        "  unit: string;",
        "  deviceClass: string;",
        "  precision: number; // display decimals",
        "  scale: number; // raw -> unit",
        "  mult: number; // HA-normalising multiplier (1 unless the unit is normalised)",
        '  dtype: "u16" | "s16";',
        "  priority: number;",
        "  enum: [number, string][] | null; // raw -> label",
        "}",
        "",
        "export const PROTECTION_READS: Record<string, ProtectionRead[]> = {",
    ]
    for family in sorted(reads):
        lines.append(f"  {_jstr(family)}: [")
        rows = sorted(reads[family].items(), key=lambda kv: (int(kv[1][_R_PRIORITY]), int(kv[1][_R_REGADDR])))
        for key, r in rows:
            acc = r[_R_ACC]
            lines.append(
                f"    {{ address: {int(r[_R_REGADDR])}, key: {_jstr(key)}, label: {_jstr(r[_R_NAME] or key)}, "
                f"unit: {_jstr(r[_R_UNIT] or '')}, deviceClass: {_jstr(r[_R_DC] or '')}, "
                f"precision: {int(acc) if acc is not None else -1}, scale: {_num(r[_R_SCALE])}, "
                f"mult: {_num(r[_R_MULT] if r[_R_MULT] is not None else 1.0)}, dtype: {_jstr(r[_R_DTYPE])}, "
                f"priority: {int(r[_R_PRIORITY])}, enum: {_enum_literal(r[_R_ENUM], enums)} }},"
            )
        lines.append("  ],")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def gen_state(fault_codes: dict, state_class: dict) -> str:
    """Emit FAULT_CODES (family -> code -> name) and STATE_CLASS (device_state code -> class
    name) from register_meta.py, for the fault list and the running-state badge."""
    lines = [
        "",
        "// --- fault-code names and running-state classes (from register_meta.py) ----------------",
        "// FAULT_CODES[family][code] names a code of the fault list (active_fault_codes /",
        "// first_fault); STATE_CLASS[code] classes a device_state (0x2086) code as RUNNING, STOPPED,",
        "// STANDBY, STARTING, TRANSIENT, FAULT or OFFLINE (unlisted codes are UNKNOWN).",
        "export const FAULT_CODES: Record<string, Record<number, string>> = {",
    ]
    for family in sorted(fault_codes):
        lines.append(f"  {_jstr(family)}: {{")
        for code, name in sorted(fault_codes[family].items(), key=lambda kv: int(kv[0])):
            lines.append(f"    {int(code)}: {_jstr(str(name))},")
        lines.append("  },")
    lines.append("};")
    lines.append("")
    lines.append("export const STATE_CLASS: Record<number, string> = {")
    for code, cls in sorted(state_class.items(), key=lambda kv: int(kv[0])):
        lines.append(f"  0x{int(code):04X}: {_jstr(str(cls))},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def gen_write(keys) -> str:
    """Emit WRITE_META: the writable-register catalogue (from write_meta.py) the Controls UI uses
    to build inputs and convert display values to raw registers before POST /api/write."""
    lines = [
        "",
        "// --- writable registers (from components/sungrow_control/write_meta.py) ----------------",
        "// Each entry drives one control in the device Controls section. The UI converts a display",
        "// value to a raw register with round(value / scale), then POSTs the raw value to",
        "// /api/write?device=&address=&value=; the on-device ControlCore gate re-checks it.",
        "export interface WriteDef {",
        "  key: string;",
        "  profile: string; // 'hybrid' | 'string'",
        "  name: string;",
        "  address: number;",
        "  type: string; // 'u16' | 's16'",
        "  rawMin: number;",
        "  rawMax: number;",
        "  values: number[]; // allowed raw values (empty = any in [rawMin, rawMax])",
        "  scale: number; // display = raw * scale ; raw = round(display / scale)",
        "  unit: string;",
        "  step: number;",
        "  numberMin: number; // display-unit range",
        "  numberMax: number;",
        "  sigid: string; // '0xNNNN' read-back signal key in /api/signals",
        "  options: [number, string][]; // raw -> label (selects / switches)",
        "}",
        "",
    ]
    if not keys:
        lines.append("export const WRITE_META: Record<string, WriteDef> = {};")
        lines.append("")
        return "\n".join(lines)

    lines.append("export const WRITE_META: Record<string, WriteDef> = {")
    for key in sorted(keys):
        m = keys[key]
        opts = "[" + ", ".join(f"[{int(r)}, {_jstr(str(t))}]" for r, t in m.get("options", [])) + "]"
        vals = "[" + ", ".join(str(int(v)) for v in m.get("values", [])) + "]"
        lines.append(
            f"  {_jstr(key)}: {{ key: {_jstr(key)}, profile: {_jstr(m['profile'])}, "
            f"name: {_jstr(m['name'])}, address: {int(m['address'])}, type: {_jstr(m['type'])}, "
            f"rawMin: {int(m['min'])}, rawMax: {int(m['max'])}, values: {vals}, "
            f"scale: {_num(m['scale'])}, unit: {_jstr(m.get('unit', ''))}, step: {_num(m['step'])}, "
            f"numberMin: {_num(m['number_min'])}, numberMax: {_num(m['number_max'])}, "
            f'sigid: "0x{int(m["sigid"]):04X}", options: {opts} }},'
        )
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate meta.gen.ts from register_meta.py.")
    ap.add_argument("--out", type=Path, default=OUT_TS, help="output TypeScript module")
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is stale")
    args = ap.parse_args()

    families, info, enums, reads = _load_meta()
    fault_codes, state_class = _load_state_meta()
    _, keys = _load_write_meta()
    content = (gen(families, info, enums) + gen_reads(reads, enums) + gen_state(fault_codes, state_class)
               + gen_write(keys))
    try:
        current = args.out.read_text(encoding="utf-8")
    except OSError:
        current = None
    if args.check:
        if current != content:
            print(f"stale: {args.out} (run tools/gen_web_meta.py)")
            return 1
        return 0
    if current == content:
        print(f"[gen_web_meta] {args.out} unchanged", file=sys.stderr)
        return 0
    args.out.write_text(content, encoding="utf-8")
    print(f"[gen_web_meta] wrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
