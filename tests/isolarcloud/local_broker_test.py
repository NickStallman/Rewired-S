#!/usr/bin/env python3
"""Local-only MQTT integration test for the isolarcloud wire format.

HARD RULE: this never talks to any Sungrow/iSolarCloud host. The broker below binds 127.0.0.1 on
an ephemeral port and both clients connect to it; there is no hostname resolution at all.

What it checks (with the payloads generated by the C++ core, `test_isolarcloud --dump`):
  * a device client connects with clientId = SN, the shared username/password, MQTT 3.1.1, clean
    session, keepalive 120 and the zlib'd will on pub/willdata (QoS1, retain);
  * every sample published by the device arrives at a "cloud" subscriber on pub/#, inflates with
    stock zlib, is NUL-terminated JSON with the expected publicData (sendTime YYYYMMDDhhmmss), the
    per-device beat / table-driven rundata have the stock shape, and the chunked rundata
    reassembles (packgeId order) into the original businessData array;
  * a zlib'd, retained 10325 getparam from the cloud on cmd/<SN>/getparam/enum_0_0_1 reaches the
    device, the C++ inbound path decodes it (`test_isolarcloud --decode`) with the reply topic
    rsp/getparam/<SN>/<own enum>, and the device's empty retained publish clears it on the broker;
  * after an abrupt device disconnect the broker fires the will, and a late subscriber gets it
    retained with beat=0.

Usage: python3 local_broker_test.py <test_isolarcloud binary> <samples dir>
Pure stdlib; the broker is a minimal MQTT 3.1.1 subset (QoS 0/1, retain, will, + and # filters).
"""

