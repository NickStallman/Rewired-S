CONNECT, CONNACK, PUBLISH, PUBACK, SUBSCRIBE, SUBACK, PINGREQ, PINGRESP, DISCONNECT = 1, 2, 3, 4, 8, 9, 12, 13, 14


# ---- codec ---------------------------------------------------------------------------------------
def enc_len(n):
    out = bytearray()
    while True:
        b = n % 128
        n //= 128
        out.append(b | (0x80 if n else 0))
        if not n:
            return bytes(out)


def enc_str(b):
    if isinstance(b, str):
        b = b.encode()
    return struct.pack(">H", len(b)) + b


def packet(ptype, flags, body):
    return bytes([(ptype << 4) | flags]) + enc_len(len(body)) + body


def recv_exact(sock, n):
    buf = b""
    while len(buf) < n:
        chunk = sock.recv(n - len(buf))
        if not chunk:
            raise ConnectionError("closed")
        buf += chunk
    return buf


def read_packet(sock):
    h = recv_exact(sock, 1)[0]
    mult, n = 1, 0
    while True:
        b = recv_exact(sock, 1)[0]
        n += (b & 0x7F) * mult
        mult *= 128
        if not b & 0x80:
            break
    return h >> 4, h & 0x0F, recv_exact(sock, n)


def take_str(body, off):
    (n,) = struct.unpack_from(">H", body, off)
    return body[off + 2 : off + 2 + n], off + 2 + n


def topic_matches(flt, topic):
    f, t = flt.split("/"), topic.split("/")
    for i, part in enumerate(f):
        if part == "#":
            return True
        if i >= len(t) or (part != "+" and part != t[i]):
            return False
    return len(f) == len(t)


# ---- broker --------------------------------------------------------------------------------------
class Broker:
    def __init__(self):
        self.srv = socket.socket()
        self.srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.srv.bind(("127.0.0.1", 0))
        self.srv.listen()
        self.port = self.srv.getsockname()[1]
        self.lock = threading.Lock()
        self.subs = []  # (conn, filter)
        self.retained = {}
        self.connects = {}  # client_id -> parsed CONNECT
        threading.Thread(target=self._accept, daemon=True).start()

    def _accept(self):
        while True:
            conn, _ = self.srv.accept()
            threading.Thread(target=self._client, args=(conn,), daemon=True).start()

    def _deliver(self, topic, payload, retain_flag=False):
        with self.lock:
            targets = [c for c, f in self.subs if topic_matches(f, topic)]
        for c in targets:
            try:
                c.sendall(packet(PUBLISH, 1 if retain_flag else 0, enc_str(topic) + payload))
            except OSError:
                pass

    def _publish(self, topic, payload, retain):
        if retain and not payload:
            self.retained.pop(topic, None)  # zero-length retained publish clears (MQTT 3.1.1 3.3.1.3)
        elif retain:
            self.retained[topic] = payload
        self._deliver(topic, payload)

    def _client(self, conn):
        will = None
        try:
            ptype, _, body = read_packet(conn)
            assert ptype == CONNECT
            name, off = take_str(body, 0)
            level, cflags = body[off], body[off + 1]
            (keepalive,) = struct.unpack_from(">H", body, off + 2)
            off += 4
            cid, off = take_str(body, off)
            info = {"proto": name.decode(), "level": level, "clean": bool(cflags & 2), "keepalive": keepalive,
                    "client_id": cid.decode()}
            if cflags & 0x04:
                wt, off = take_str(body, off)
                wm, off = take_str(body, off)
                will = (wt.decode(), wm, (cflags >> 3) & 3, bool(cflags & 0x20))
                info["will"] = will
            if cflags & 0x80:
                u, off = take_str(body, off)
                info["username"] = u.decode()
            if cflags & 0x40:
                p, off = take_str(body, off)
                info["password"] = p.decode()
            self.connects[info["client_id"]] = info
            conn.sendall(packet(CONNACK, 0, b"\x00\x00"))
            while True:
                ptype, flags, body = read_packet(conn)
                if ptype == PUBLISH:
                    qos = (flags >> 1) & 3
                    t, off = take_str(body, 0)
                    if qos:
                        pid = body[off : off + 2]
                        off += 2
                        conn.sendall(packet(PUBACK, 0, pid))
                    self._publish(t.decode(), body[off:], bool(flags & 1))
                elif ptype == SUBSCRIBE:
                    pid, off, granted = body[:2], 2, bytearray()
                    new = []
                    while off < len(body):
                        f, off = take_str(body, off)
                        granted.append(min(body[off], 0))  # we deliver QoS 0
                        off += 1
                        new.append(f.decode())
                    with self.lock:
                        self.subs += [(conn, f) for f in new]
                    conn.sendall(packet(SUBACK, 0, pid + bytes(granted)))
                    for f in new:
                        for t, p in list(self.retained.items()):
                            if topic_matches(f, t):
                                conn.sendall(packet(PUBLISH, 1, enc_str(t) + p))
                elif ptype == PINGREQ:
                    conn.sendall(packet(PINGRESP, 0, b""))
                elif ptype == DISCONNECT:
                    will = None  # clean disconnect: no will
                    return
        except (ConnectionError, OSError, AssertionError):
            pass
        finally:
            with self.lock:
                self.subs = [(c, f) for c, f in self.subs if c is not conn]
            conn.close()
            if will:
                self._publish(will[0], will[1], will[3])


# ---- client --------------------------------------------------------------------------------------
class Client:
    def __init__(self, port, client_id, username=None, password=None, will=None, keepalive=120):
        self.sock = socket.create_connection(("127.0.0.1", port), timeout=5)
        flags = 0x02
        payload = enc_str(client_id)
        if will:
            topic, msg, qos, retain = will
            flags |= 0x04 | (qos << 3) | (0x20 if retain else 0)
            payload += enc_str(topic) + enc_str(msg)
        if username is not None:
            flags |= 0x80
            payload += enc_str(username)
        if password is not None:
            flags |= 0x40
            payload += enc_str(password)
        self.sock.sendall(packet(CONNECT, 0, enc_str("MQTT") + bytes([4, flags]) + struct.pack(">H", keepalive) + payload))
        ptype, _, body = read_packet(self.sock)
        assert ptype == CONNACK and body[1] == 0, "CONNACK refused"
        self.msgs = queue.Queue()
        self.pid = 1
        threading.Thread(target=self._rx, daemon=True).start()

    def _rx(self):
        try:
            while True:
                ptype, flags, body = read_packet(self.sock)
                if ptype == PUBLISH:
                    t, off = take_str(body, 0)
                    if (flags >> 1) & 3:
                        off += 2
                    self.msgs.put((t.decode(), body[off:], bool(flags & 1)))
        except (ConnectionError, OSError):
            pass

    def subscribe(self, flt):
        self.sock.sendall(packet(SUBSCRIBE, 2, struct.pack(">H", self.pid) + enc_str(flt) + b"\x01"))
        self.pid += 1

    def publish(self, topic, payload, qos=1, retain=False):
        body = enc_str(topic) + (struct.pack(">H", self.pid) if qos else b"") + payload
        self.pid += 1
        self.sock.sendall(packet(PUBLISH, (qos << 1) | (1 if retain else 0), body))

    def get(self, timeout=3):
        return self.msgs.get(timeout=timeout)


# ---- test ----------------------------------------------------------------------------------------
FAILS = []


def check(cond, what):
    print(("  ok    " if cond else "  FAIL  ") + what)
    if not cond:
        FAILS.append(what)


def unwire(payload, compress):
    data = zlib.decompress(payload) if compress else payload
    if compress:
        check(data.endswith(b"\x00"), "compressed payload carries the trailing NUL (stock strlen+1)")
    return json.loads(data.rstrip(b"\x00"))


def main():
    harness, samples = sys.argv[1], sys.argv[2]
    rows = [line.rstrip("\n").split("\t") for line in open(os.path.join(samples, "index.tsv"))]
    blobs = [(t, open(os.path.join(samples, f), "rb").read(), int(c)) for t, f, c, _ in rows]
    will_topic, will_payload, _ = blobs[0]

    broker = Broker()
    print(f"broker on 127.0.0.1:{broker.port}")
    cloud = Client(broker.port, "cloud-test")
    cloud.subscribe("isolarcloud/devicedata/pub/#")
    device = Client(broker.port, SN, USERNAME, PASSWORD, will=(will_topic, will_payload, 1, True))
    cmd_topic = f"isolarcloud/devicedata/cmd/{SN}/getparam/enum_0_0_1"
    device.subscribe(f"isolarcloud/devicedata/cmd/{SN}/+/enum_0_0_1")
    device.subscribe("isolarcloud/devicedata/cmd/8/enum_0_0_0")

    import time

    time.sleep(0.2)
    info = broker.connects[SN]
    check(info["proto"] == "MQTT" and info["level"] == 4, "CONNECT is MQTT 3.1.1 (level 4)")
    check(info["clean"] and info["keepalive"] == 120, "clean session, keepalive 120")
    check(info.get("username") == USERNAME and info.get("password") == PASSWORD, "shared username/password")
    wt, wm, wq, wr = info["will"]
    check(wt == f"isolarcloud/devicedata/pub/willdata/{SN}/enum_0_0_1" and wq == 1 and wr, "will topic, QoS1, retain")
    w = unwire(wm, 1)
    check(w["businessData"] == [{"devCode": 247, "devType": 22, "beat": 0}], "will businessData beat=0")
    check(w["publicData"] == {"productType": "1824", "productName": "WiNet-S2", "productSN": SN,
                              "sendTime": "20261018123456"}, "will publicData (sendTime YYYYMMDDhhmmss)")

    # Device -> cloud
    for t, p, _ in blobs[1:]:
        device.publish(t, p)
    got = [cloud.get() for _ in blobs[1:]]
    check([g[0] for g in got] == [b[0] for b in blobs[1:]], "all samples delivered on their topics")
    beat = unwire(got[0][1], 1)
    check(beat["businessData"] == [{"devCode": 247, "devType": 22, "beat": 1}, {"devCode": 1, "devType": 14, "beat": 1}],
          "beatdata: one element per device, logger first")
    rd = unwire(got[1][1], 1)
    check(rd["businessData"] == [{"devCode": 1, "devType": 14, "dataTime": "20261018123000", "data": {"13019": "-0.5"}}],
          "rundata: one device per message, point-id keys, string values")
    parts = [unwire(g[1], 1) for g in got[2:]]
    check(len({p["messageId"] for p in parts}) == 1, "chunks share messageId")
    check(all(p["packgeCount"] == str(len(parts)) for p in parts), f"packgeCount == {len(parts)}")
    joined = "".join(p["businessData"] for p in sorted(parts, key=lambda p: int(p["packgeId"])))
    bd = json.loads(joined)
    check(isinstance(bd, list) and len(bd) == 300, "chunked rundata reassembles to 300 entries")

    # Cloud -> device command (zlib, like the topic says), retained like the cloud is suspected to (N5)
    cmd = {"messageId": "cloud_1", "businessData": [{"cmdType": "10325", "batchId": "it-1", "devCode": 1,
                                                     "mode": 0, "readOnly": 1,
                                                     "data": {"p1": {"modbusAddress": "5000", "dataType": "4"}}}]}
    cloud.publish(cmd_topic, zlib.compress(json.dumps(cmd).encode() + b"\x00"), retain=True)
    t, p, _ = device.get()
    check(t == cmd_topic, "device received the getparam command")
    with tempfile.NamedTemporaryFile(delete=False) as f:
        f.write(p)
    out = subprocess.run([harness, "--decode", t, f.name], capture_output=True, text=True).stdout
    os.unlink(f.name)
    kv = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
    check(kv.get("status") == "ok" and kv.get("cmdType") == "10325" and kv.get("batchId") == "it-1",
          "C++ inbound path decodes the command")
    check(kv.get("reply_topic") == f"isolarcloud/devicedata/rsp/getparam/{SN}/enum_0_0_1",
          "getparam reply goes to rsp/getparam with our enum (C23)")
    reply = json.loads(kv.get("reply", "null"))
    check(reply == [{"batchId": "it-1", "cmdType": "10325", "dataTime": "20261018123456", "result": 1}],
          "reply header: batchId, cmdType, dataTime, numeric result")
    check(cmd_topic in broker.retained, "command is retained on the broker")
    device.publish(cmd_topic, b"", qos=1, retain=True)  # the retained command is cleared after every dispatch, as the stock dongle does
    time.sleep(0.2)
    check(cmd_topic not in broker.retained, "device's empty retained publish clears the command")

    # Abrupt disconnect -> will (retained) to a late subscriber
    device.sock.shutdown(socket.SHUT_RDWR)
    device.sock.close()
    t, p, _ = cloud.get()
    check(t == will_topic and unwire(p, 1)["businessData"][0]["beat"] == 0, "will delivered on abrupt disconnect")
    late = Client(broker.port, "late")
    late.subscribe(will_topic)
    t, p, retained = late.get()
    check(t == will_topic and retained, "late subscriber gets the retained will")

    print(f"local broker test: {'PASS' if not FAILS else 'FAIL'} ({len(FAILS)} failures)")
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main())
