#!/usr/bin/env python3
"""Generate components/sungrow_mqtt/ha_meta_gen.h, the baked HA discovery-metadata table.

Input: components/sungrow_datamodel/register_meta.py (names, units, classes, precision, enum
tables, static / hidden groups) and components/sungrow_mqtt/deadband.py (publish deadband per
signal). Both are loaded by path, so this runs with the standard library alone; the sungrow_mqtt
component imports it at ESPHome config load and calls write_if_changed().

Usage: python3 components/sungrow_mqtt/ha_meta_gen.py [--check]
  --check   exit 1 if the committed header differs from the generated one (used by the tests).
"""

import argparse
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REGISTER_META = HERE.parent / "sungrow_datamodel" / "register_meta.py"
DEADBAND = HERE / "deadband.py"
OUT = HERE / "ha_meta_gen.h"

# register_meta tuple layout (see register_meta.py docstring):
#   (sigid, name, unit, multiplier, device_class, state_class, accuracy, is_string, type, nreg,
#    bit_parent, bit)
_I_SIGID, _I_NAME, _I_UNIT, _I_MULT, _I_DC, _I_SC, _I_ACC, _I_IS_STR = range(8)
_I_BIT = 11


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_rm = _load("sungrow_register_meta", REGISTER_META)
_deadband = _load("sungrow_mqtt_deadband", DEADBAND).deadband
FAMILIES = _rm.FAMILIES


def _csym(name: str) -> str:
    """C identifier from an enum name."""
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def _collect_enums():
    """register_meta.ENUMS as {name: [(raw, label), ...]}."""
    return {name: [(int(r), str(t)) for r, t in pairs]
            for name, pairs in (getattr(_rm, "ENUMS", {}) or {}).items()}


def _enum_name_for(family: str, key: str):
    ref = getattr(_rm, "ENUM_SIGNALS", {}) or {}
    return ref.get(family, {}).get(key)


def _is_diagnostic(family: str, key: str) -> bool:
    """group=="static" signals (model, serial, firmware, ratings) -> HA entity_category diagnostic."""
    groups = getattr(_rm, "GROUPS", {}) or {}
    return groups.get(family, {}).get(key) == "static"


def _is_hidden(family: str, key: str) -> bool:
    """group=="hidden" signals (undecodable function_flags, redundant total_yield variants, the
    remote-server connection status) are never surfaced anywhere: skipped from MQTT discovery
    entirely (no config, no state), matching the SPA which filters group=="hidden" from all lists."""
    groups = getattr(_rm, "GROUPS", {}) or {}
    return groups.get(family, {}).get(key) == "hidden"


def _slug(label: str) -> str:
    """sensor_slug from a label: lowercase, non-alphanumeric -> '_', collapsed and trimmed."""
    s = re.sub(r"[^a-z0-9]+", "_", label.lower())
    return s.strip("_")


def _cstr(s: str) -> str:
    """C++ narrow-string literal body (UTF-8 bytes kept verbatim; only \\ and " escaped)."""
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _cfloat(x) -> str:
    """C++ float literal; repr(float) always yields a '.'/'e' so the 'f' suffix is valid."""
    return repr(float(x)) + "f"


def gen_header() -> str:
    lines = [
        "// GENERATED by components/sungrow_mqtt/ha_meta_gen.py from "
        "components/sungrow_datamodel/register_meta.py - DO NOT EDIT.",
        "// Baked discovery-metadata table for the per-device MQTT publisher (discovery_meta.h).",
        "#pragma once",
        "namespace esphome {",
        "namespace sungrow_mqtt {",
        "",
    ]

    all_enums = _collect_enums()
    used_enums = set()  # only emit maps actually referenced by a signal (avoids unused warnings)

    # First pass: resolve every published signal's row fields (so we know which enum maps are used).
    family_defs = []  # (family, [(row_fields_dict)])
    for family in sorted(FAMILIES):
        seen = set()
        sigs = []
        for key, meta in FAMILIES[family].items():
            if len(meta) > _I_BIT and meta[_I_BIT] is not None and meta[_I_BIT] >= 0:
                continue  # bitfield child
            if _is_hidden(family, key):
                continue  # group=="hidden": never published to MQTT/HA
            sigid = meta[_I_SIGID]
            if sigid in seen:
                continue
            seen.add(sigid)
            is_str = bool(meta[_I_IS_STR])
            enum_name = None if is_str else _enum_name_for(family, key)
            if enum_name is not None and enum_name in all_enums:
                used_enums.add(enum_name)
            else:
                enum_name = None
            precision = int(meta[_I_ACC]) if meta[_I_ACC] is not None else -1
            sigs.append({
                "sigid": sigid,
                "name": meta[_I_NAME] or key,
                "slug": _slug(meta[_I_NAME] or key) or _slug(key),
                "unit": meta[_I_UNIT] or "",
                "mult": float(meta[_I_MULT]) if meta[_I_MULT] is not None else 1.0,
                "dc": meta[_I_DC] or "",
                "sc": meta[_I_SC] or "",
                "precision": precision,
                "deadband": _deadband(meta[_I_UNIT] or "", precision, meta[_I_DC] or "",
                                      meta[_I_SC] or "", is_str, enum_name is not None),
                "is_str": "true" if is_str else "false",
                "enum": enum_name,
                "diag": "true" if _is_diagnostic(family, key) else "false",
            })
        family_defs.append((family, sigs))

    # Emit the referenced enum maps.
    for name in sorted(used_enums):
        sym = _csym(name)
        entries = ", ".join(f'{{0x{raw:04X}, "{_cstr(str(label))}"}}' for raw, label in all_enums[name])
        lines.append(f"static const EnumEntry ENUM_ENTRIES_{sym}[] = {{{entries}}};")
        lines.append(
            f"static const EnumMap HA_ENUM_{sym} = {{ENUM_ENTRIES_{sym}, "
            f"{len(all_enums[name])}}};"
        )
    if used_enums:
        lines.append("")

    family_rows = []
    for family, sigs in family_defs:
        rows = []
        for s in sigs:
            enum_ref = f"&HA_ENUM_{_csym(s['enum'])}" if s["enum"] else "nullptr"
            rows.append(
                f'  {{0x{s["sigid"]:04X}, "{_cstr(s["name"])}", "{_cstr(s["slug"])}", '
                f'"{_cstr(s["unit"])}", {_cfloat(s["mult"])}, "{_cstr(s["dc"])}", '
                f'"{_cstr(s["sc"])}", {s["precision"]}, {_cfloat(s["deadband"])}, {s["is_str"]}, '
                f'{enum_ref}, {s["diag"]}}},'
            )
        arr = f"HA_META_{family}"
        lines.append(f"static const SensorMeta {arr}[] = {{")
        lines.extend(rows)
        lines.append("};")
        lines.append("")
        family_rows.append((family, arr, len(rows)))

    lines.append("static const FamilyMeta HA_FAMILIES[] = {")
    for family, arr, n in family_rows:
        lines.append(f'  {{"{family}", {arr}, {n}}},')
    lines.append("};")
    lines.append(f"static constexpr uint16_t HA_FAMILY_COUNT = {len(family_rows)};")
    lines.append("")
    lines.append("}  // namespace sungrow_mqtt")
    lines.append("}  // namespace esphome")
    lines.append("")
    return "\n".join(lines)


def write_if_changed(path: Path = OUT) -> bool:
    """Write the header when its content differs; True if it was (re)written."""
    content = gen_header()
    try:
        if path.read_text(encoding="utf-8") == content:
            return False
    except OSError:
        pass
    path.write_text(content, encoding="utf-8")
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed header is not up to date")
    a = ap.parse_args(argv)
    if a.check:
        try:
            current = OUT.read_text(encoding="utf-8")
        except OSError:
            current = None
        if current != gen_header():
            print("stale: %s (run components/sungrow_mqtt/ha_meta_gen.py)" % OUT)
            return 1
        return 0
    if write_if_changed():
        print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
