"""sungrow_web: serve our own single-page app (SPA) from the device, replacing ESPHome's
web_server landing page, with a JSON API over the live device inventory and signals and, when a
sungrow_control is bound, the write / Installer / Setup endpoints.

It does NOT replace web_server — web_server keeps running (/events, the REST API, OTA via
api:/ota:, etc.). This component only registers one extra AsyncWebHandler on web_server_base
that wins a strict whitelist of exact paths (/, /index.html, the hashed app.<hash>.js/.css,
GET /api/devices, /api/signals, /api/grid_read, /api/setup_options, /api/setup_preview,
/api/capture, /api/capture_meta, /api/capture_file, /api/diag_send, /api/diag_report,
/api/web_login, /api/mqtt_settings, /api/cloud_version; POST /api/write, /api/confirm,
/api/setup_write, /api/grid_read_start, /api/setup_apply, /api/setup_start, /api/capture_start,
/api/capture_cancel, /api/diag_send, /api/web_login, /api/mqtt_settings, /api/cloud_version).
Because it runs at
setup priority 251 (> web_server's 249) its handler is
flushed/registered first, so it owns "/". Everything else falls through unchanged.

Writes from these endpoints are authorised by the web login (Setup / Installer also by a confirm
token) and do not use sungrow_control's `writes_enabled` switch, which gates MQTT, Modbus-TCP and
the HA action; the allow-list, range and online checks apply.

    sungrow_web:
      id: web_ui
      sungrow_modbus_id: rs485_hub       # live device inventory (/api/devices)
      sungrow_datamodel_id: sungrow_dm   # live signals (/api/signals)
      # login: yaml                      # yaml: web_server.auth as compiled (default)
      #                                  # runtime: the pair stored in NVS from the Settings page
      #                                  #   (pre-built images); web_server.auth then holds
      #                                  #   placeholders that apply until a pair is stored

Requires web_server: to be configured (that is what starts the HTTP server + digest auth and
creates global_web_server_base). The embedded SPA bytes live in web_assets.h, generated by
tools/gen_web_assets.py from the TypeScript project in web/.
"""

import esphome.codegen as cg
import esphome.config_validation as cv
from esphome.const import CONF_ID

from esphome.components.sungrow_datamodel import CONF_SUNGROW_DATAMODEL_ID, SungrowDataModel
from esphome.components.sungrow_modbus import SungrowModbus

CODEOWNERS = []
DEPENDENCIES = ["web_server_base", "sungrow_modbus", "sungrow_datamodel"]

sungrow_web_ns = cg.esphome_ns.namespace("sungrow_web")
SungrowWeb = sungrow_web_ns.class_("SungrowWeb", cg.Component)

# Optional sibling for inverter writes (the POST endpoints). Referenced by class only
# (no Python import / hard dependency), matching how sungrow_mqtt binds its siblings.
SungrowControl = cg.esphome_ns.namespace("sungrow_control").class_("SungrowControl", cg.Component)
# Optional sibling for the diagnostic captures (I-V scan, grid waveform; /api/capture*).
SungrowCapture = cg.esphome_ns.namespace("sungrow_capture").class_("SungrowCapture", cg.Component)
# Optional sibling for the diagnostics report upload (/api/diag_send, /api/diag_report).
SungrowAnalytics = cg.esphome_ns.namespace("sungrow_analytics").class_("SungrowAnalytics", cg.Component)
# Optional siblings for the Settings page: MQTT broker settings (/api/mqtt_settings) and the
# cloud identity reload after a version override (/api/cloud_version).
SungrowMqttComponent = cg.esphome_ns.namespace("sungrow_mqtt").class_("SungrowMqttComponent", cg.Component)
IsolarcloudComponent = cg.esphome_ns.namespace("isolarcloud").class_("IsolarcloudComponent", cg.Component)
# Optional: the native OTA component whose password follows the runtime web login (ota_id).
ESPHomeOTAComponent = cg.esphome_ns.namespace("esphome").class_("ESPHomeOTAComponent", cg.Component)

CONF_SUNGROW_MODBUS_ID = "sungrow_modbus_id"
CONF_SUNGROW_CONTROL_ID = "sungrow_control_id"
CONF_SUNGROW_CAPTURE_ID = "sungrow_capture_id"
CONF_SUNGROW_ANALYTICS_ID = "sungrow_analytics_id"
CONF_SUNGROW_MQTT_ID = "sungrow_mqtt_id"
CONF_ISOLARCLOUD_ID = "isolarcloud_id"
CONF_OTA_ID = "ota_id"
CONF_LOGIN = "login"
LOGIN_YAML = "yaml"
LOGIN_RUNTIME = "runtime"

CONFIG_SCHEMA = cv.Schema(
    {
        cv.GenerateID(): cv.declare_id(SungrowWeb),
        cv.GenerateID(CONF_SUNGROW_MODBUS_ID): cv.use_id(SungrowModbus),
        cv.GenerateID(CONF_SUNGROW_DATAMODEL_ID): cv.use_id(SungrowDataModel),
        # Optional: when a sungrow_control is configured, the SPA exposes the write UI. Defaults to
        # the single configured instance (resolved in to_code).
        cv.Optional(CONF_SUNGROW_CONTROL_ID): cv.use_id(SungrowControl),
        # Optional: when a sungrow_capture is configured, the SPA shows the Captures page.
        cv.Optional(CONF_SUNGROW_CAPTURE_ID): cv.use_id(SungrowCapture),
        # Optional: when a sungrow_analytics is configured, Settings offers "Send diagnostics".
        cv.Optional(CONF_SUNGROW_ANALYTICS_ID): cv.use_id(SungrowAnalytics),
        # Optional: sungrow_mqtt (Settings page broker form) and isolarcloud (identity reload).
        cv.Optional(CONF_SUNGROW_MQTT_ID): cv.use_id(SungrowMqttComponent),
        cv.Optional(CONF_ISOLARCLOUD_ID): cv.use_id(IsolarcloudComponent),
        # With login: runtime, keep this native OTA's password equal to the web login password
        # (the ota block needs `password: ""` so its auth path is compiled).
        cv.Optional(CONF_OTA_ID): cv.use_id(ESPHomeOTAComponent),
        # runtime: the digest login is the pair stored in NVS (changed on the Settings page,
        # POST /api/web_login); web_server.auth supplies the placeholders used until then.
        cv.Optional(CONF_LOGIN, default=LOGIN_YAML): cv.one_of(LOGIN_YAML, LOGIN_RUNTIME, lower=True),
    }
).extend(cv.COMPONENT_SCHEMA)


def _validate(config):
    from esphome.core import CORE

    # The SPA handler attaches to global_web_server_base, which only exists when web_server:
    # is configured (web_server_base alone does not start a listener). Mirror the check in
    # components/sungrow_debug/__init__.py.
    if "web_server" not in CORE.loaded_integrations:
        raise cv.Invalid("sungrow_web needs web_server: (it serves the SPA on the web server, behind its auth)")
    if config[CONF_LOGIN] == LOGIN_RUNTIME:
        import esphome.final_validate as fv

        auth = (fv.full_config.get().get("web_server") or {}).get("auth")
        if not auth or auth.get("type") != "digest":
            raise cv.Invalid(
                "sungrow_web login: runtime needs web_server.auth with type: digest (its username/password "
                "are the placeholders used until a login is stored)"
            )
    if CONF_OTA_ID in config:
        import esphome.final_validate as fv

        if config[CONF_LOGIN] != LOGIN_RUNTIME:
            raise cv.Invalid("sungrow_web ota_id only makes sense with login: runtime")
        for ota in fv.full_config.get().get("ota") or []:
            if ota.get("platform") == "esphome" and str(ota.get(CONF_ID)) == str(config[CONF_OTA_ID]):
                if "password" not in ota:
                    raise cv.Invalid(
                        "sungrow_web ota_id: that ota block needs `password: \"\"` so its auth path is compiled"
                    )
                if "encryption" in ota:
                    raise cv.Invalid("sungrow_web ota_id: that ota block must not require encryption")
    return config


FINAL_VALIDATE_SCHEMA = _validate


async def to_code(config):
    cg.add_define("USE_SUNGROW_WEB")
    var = cg.new_Pvariable(config[CONF_ID])
    await cg.register_component(var, config)

    if config[CONF_LOGIN] == LOGIN_RUNTIME:
        from esphome.core import CORE

        auth = CORE.config["web_server"]["auth"]
        cg.add_define("SUNGROW_WEB_RUNTIME_LOGIN")
        cg.add(var.set_default_login(auth["username"], auth["password"]))
        if CONF_OTA_ID in config:
            cg.add_define("SUNGROW_WEB_BIND_OTA")
            cg.add(var.set_ota(await cg.get_variable(config[CONF_OTA_ID])))

    modbus = await cg.get_variable(config[CONF_SUNGROW_MODBUS_ID])
    cg.add(var.set_modbus(modbus))
    dm = await cg.get_variable(config[CONF_SUNGROW_DATAMODEL_ID])
    cg.add(var.set_datamodel(dm))

    # Bind sungrow_control when present (explicit id, else the single configured instance), which
    # enables the write / Installer / Setup endpoints. Without it they report "unavailable".
    ctl_id = config.get(CONF_SUNGROW_CONTROL_ID)
    if ctl_id is None:
        from esphome.core import CORE

        conf = CORE.config.get("sungrow_control")
        if isinstance(conf, list):
            conf = conf[0] if len(conf) == 1 else None
        if conf:
            ctl_id = conf[CONF_ID]
    if ctl_id is not None:
        cg.add_define("SUNGROW_WEB_BIND_CONTROL")
        cg.add(var.set_control(await cg.get_variable(ctl_id)))

    # Bind sungrow_capture the same way (Captures page and /api/capture*).
    cap_id = config.get(CONF_SUNGROW_CAPTURE_ID)
    if cap_id is None:
        from esphome.core import CORE

        conf = CORE.config.get("sungrow_capture")
        if isinstance(conf, list):
            conf = conf[0] if len(conf) == 1 else None
        if conf:
            cap_id = conf[CONF_ID]
    if cap_id is not None:
        cg.add_define("SUNGROW_WEB_BIND_CAPTURE")
        cg.add(var.set_capture(await cg.get_variable(cap_id)))

    # Bind sungrow_analytics the same way (/api/diag_send and /api/diag_report).
    an_id = config.get(CONF_SUNGROW_ANALYTICS_ID)
    if an_id is None:
        from esphome.core import CORE

        conf = CORE.config.get("sungrow_analytics")
        if isinstance(conf, list):
            conf = conf[0] if len(conf) == 1 else None
        if conf:
            an_id = conf[CONF_ID]
    if an_id is not None:
        cg.add_define("SUNGROW_WEB_BIND_ANALYTICS")
        cg.add(var.set_analytics(await cg.get_variable(an_id)))

    for key, domain, define, setter in (
        (CONF_SUNGROW_MQTT_ID, "sungrow_mqtt", "SUNGROW_WEB_BIND_MQTT", var.set_mqtt),
        (CONF_ISOLARCLOUD_ID, "isolarcloud", "SUNGROW_WEB_BIND_CLOUD", var.set_cloud),
    ):
        sib_id = config.get(key)
        if sib_id is None:
            from esphome.core import CORE

            conf = CORE.config.get(domain)
            if isinstance(conf, list):
                conf = conf[0] if len(conf) == 1 else None
            if conf:
                sib_id = conf[CONF_ID]
        if sib_id is not None:
            cg.add_define(define)
            cg.add(setter(await cg.get_variable(sib_id)))
